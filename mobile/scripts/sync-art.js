// node scripts/sync-art.js — copy the website's artwork (../public) into the app and write src/lib/art.ts, a map from the
// website path ("/icons/gym.webp") to a bundled require(), so every picture works offline on the phone.
// Re-run after adding artwork to the website.
const fs = require('fs');
const path = require('path');

const pub = path.resolve(__dirname, '../../public');
const out = path.resolve(__dirname, '../assets/web');
const dirs = ['icons', 'exercises', 'food', 'stalls', 'muscles', 'empty', 'avatars', 'sounds', 'quest'];
const lines = [];
for (const d of dirs) {
  fs.mkdirSync(path.join(out, d), { recursive: true });
  for (const f of fs.readdirSync(path.join(pub, d)).sort()) {
    fs.copyFileSync(path.join(pub, d, f), path.join(out, d, f));
    lines.push(`  '/${d}/${f}': require('../../assets/web/${d}/${f}'),`);
  }
}
for (const f of ['icon-512.png', 'welcome.webp']) {
  fs.copyFileSync(path.join(pub, f), path.join(out, f));
  lines.push(`  '/${f}': require('../../assets/web/${f}'),`);
}
fs.writeFileSync(path.resolve(__dirname, '../src/lib/art.ts'),
  `// Generated by scripts/sync-art.js from the website's public/ folder. Do not edit.\nexport const art: Record<string, number> = {\n${lines.join('\n')}\n};\n`);
console.log(`${lines.length} files`);
